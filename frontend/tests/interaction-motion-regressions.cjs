const assert = require('node:assert/strict');
const { chromium } = require(process.env.RAILETA_PLAYWRIGHT_PATH || 'playwright');

(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const errors = [];
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    page.on('pageerror', error => errors.push(error.message));
    const trains = Array.from({ length: 10 }, (_, i) => ({ train_number: String(12000 + i), train_name: `Test service ${i}`, current_station: 'MAS', delay_minutes: i * 7 }));
    let refreshes = 0;
    await page.route('**/api/v1/corridor/**', route => { refreshes++; return route.fulfill({ json: { data_mode: 'historical_replay', trains } }); });
    await page.goto('http://127.0.0.1:3000/');
    await page.locator('#hero-title.is-visible').waitFor();
    const letters = page.locator('#hero-title .reveal-char');
    assert.ok(await letters.count() > 20);
    assert.notEqual(await letters.first().evaluate(el => getComputedStyle(el).animationDelay), await letters.last().evaluate(el => getComputedStyle(el).animationDelay));
    await page.waitForFunction(() => [...document.querySelectorAll('#hero-title .reveal-char')].every(el => getComputedStyle(el).opacity === '1'));
    const button = page.locator('.hero-actions .kiro-button');
    const fill = button.locator('.kiro-button-fill');
    assert.equal(await fill.evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(255, 255, 255)');
    assert.equal(await fill.evaluate(el => getComputedStyle(el).transitionDuration), '0.35s');
    assert.equal(await fill.evaluate(el => new DOMMatrix(getComputedStyle(el).transform).a), 0);
    await button.screenshot({ path: 'logs/button-purple-rest.png' });
    await button.hover();
    await page.waitForFunction(() => new DOMMatrix(getComputedStyle(document.querySelector('.hero-actions .kiro-button-fill')).transform).a > 0);
    await button.screenshot({ path: 'logs/button-purple-transition.png', animations: 'allow' });
    await page.waitForFunction(() => Math.abs(new DOMMatrix(getComputedStyle(document.querySelector('.hero-actions .kiro-button-fill')).transform).a - 1.5) < .001);
    assert.equal(await button.evaluate(el => getComputedStyle(el).color), 'rgb(0, 0, 0)');
    await button.screenshot({ path: 'logs/button-purple-hover.png' });
    await page.mouse.move(0, 0);
    await page.waitForFunction(() => new DOMMatrix(getComputedStyle(document.querySelector('.hero-actions .kiro-button-fill')).transform).a === 0);
    assert.equal(await button.evaluate(el => getComputedStyle(el).color), 'rgb(255, 255, 255)');
    const navButton = page.getByRole('button', { name: 'Find a train', exact: true });
    await navButton.focus();
    await page.waitForFunction(() => Math.abs(new DOMMatrix(getComputedStyle(document.querySelector('.nav-cta .kiro-button-fill')).transform).a - 1.5) < .001);
    assert.equal(await navButton.evaluate(el => getComputedStyle(el).color), 'rgb(255, 255, 255)');
    assert.equal(await navButton.locator('.kiro-button-fill').evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(145, 71, 255)');
    await navButton.click();
    const input = page.getByRole('textbox', { name: 'Train number' });
    assert.equal(await input.evaluate(el => document.activeElement === el), true);
    await input.fill('12000');
    await page.getByRole('button', { name: 'Clear train number' }).click();
    assert.equal(await input.inputValue(), '');
    await input.evaluate(el => el.blur());
    await page.keyboard.press('/');
    assert.equal(await input.evaluate(el => document.activeElement === el), true);
    const submit = page.getByRole('button', { name: 'Explore train', exact: true });
    assert.equal(await submit.isDisabled(), true);
    assert.equal(await submit.locator('.kiro-button-fill').evaluate(el => new DOMMatrix(getComputedStyle(el).transform).a), 0);
    await page.locator('.roster-train').first().waitFor();
    assert.equal(await page.locator('.roster-train').count(), 6);
    await page.getByRole('button', { name: 'Show all 10 trains', exact: true }).click();
    assert.equal(await page.locator('.roster-train').count(), 10);
    await page.getByRole('combobox', { name: 'Sort trains' }).selectOption('delay');
    assert.equal(await page.locator('.roster-train .train-number').first().innerText(), '12009');
    await page.getByRole('combobox', { name: 'Sort trains' }).selectOption('number');
    assert.equal(await page.locator('.roster-train .train-number').first().innerText(), '12000');
    await page.getByRole('button', { name: 'Show fewer trains', exact: true }).click();
    assert.equal(await page.locator('.roster-train').count(), 6);
    const before = refreshes;
    await page.getByRole('button', { name: 'Refresh train list' }).click();
    await page.locator('.roster-train').first().waitFor();
    assert.ok(refreshes > before);
    const track = page.getByRole('navigation', { name: 'Page journey navigation' });
    assert.equal(await track.getByRole('link').count(), 3);
    await track.getByRole('link', { name: /Read the prediction/ }).click();
    assert.equal(new URL(page.url()).hash, '#how-it-works');
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.reload();
    await page.locator('#hero-title').waitFor();
    assert.ok(await letters.first().evaluate(el => getComputedStyle(el).opacity === '1'));
    assert.ok(await fill.evaluate(el => parseFloat(getComputedStyle(el).transitionDuration) < .001));
    for (const width of [390, 320]) {
      await page.setViewportSize({ width, height: 844 });
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
      await page.locator('.track-journey').scrollIntoViewIfNeeded();
      await page.locator('.track-journey').screenshot({ path: `logs/tracks-${width}.png` });
    }
    assert.deepEqual(errors, []);
    console.log('Passed: staggered text; 350ms circular hover fill and color inversion; keyboard focus; disabled/reduced-motion states; search shortcut and clear; sorting; show all; refresh; track navigation; mobile fit.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
